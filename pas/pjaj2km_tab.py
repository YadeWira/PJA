#!/usr/bin/env python3
"""Writes pjaj2km_tab.h: the constant tables of stream version 8's model
(pjaj2kmc.c), made here once so that no platform computes them at run time.

  J2KM_ST[p >> 4]   stretch of a 16-bit probability p, in 1/256 of a logit:
                    round(256 ln(q / (1 - q))), q = ((p >> 4) + 0.5) / 4096
  J2KM_SQ[x + 3072] squash of x in [-3072, 3071] (1/256 of a logit) to a
                    16-bit probability: round(65536 / (1 + e^(-x/256))),
                    held to [1, 65535]
  J2KM_RC[n]        a counter's rate after n updates: round(65536 / (n + 1.5))

  python3 pas/pjaj2km_tab.py > pas/pjaj2km_tab.h"""
import math
def rows(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append('  ' + ','.join(str(v) for v in vals[i:i + per]) + ',')
    return '\n'.join(out)
st = [round(256 * math.log(((i + 0.5) / 4096) / (1 - (i + 0.5) / 4096))) for i in range(4096)]
sq = [min(65535, max(1, round(65536 / (1 + math.exp(-x / 256))))) for x in range(-3072, 3072)]
rc = [round(65536 / (n + 1.5)) for n in range(256)]
print('/* generated by pjaj2km_tab.py: do not edit */')
print('static const int16_t J2KM_ST[4096] = {\n' + rows(st) + '\n};')
print('static const uint16_t J2KM_SQ[6144] = {\n' + rows(sq) + '\n};')
print('static const int32_t J2KM_RC[256] = {\n' + rows(rc) + '\n};')
